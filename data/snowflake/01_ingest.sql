-- Snowflake ingestion of the S3 lake written by LakeExportJob (NDJSON.gz, Hive partitions dt=/hour=).
-- Run as SYSADMIN. Replace <ACCOUNT_ROLE_ARN> with the output `snowflake_storage_role_arn` from OpenTofu.
CREATE DATABASE IF NOT EXISTS CARDFLOW;
CREATE SCHEMA   IF NOT EXISTS CARDFLOW.RAW;
CREATE SCHEMA   IF NOT EXISTS CARDFLOW.CURATED;

CREATE STORAGE INTEGRATION IF NOT EXISTS CARDFLOW_S3
  TYPE = EXTERNAL_STAGE STORAGE_PROVIDER = 'S3' ENABLED = TRUE
  STORAGE_AWS_ROLE_ARN = '<ACCOUNT_ROLE_ARN>'
  STORAGE_ALLOWED_LOCATIONS = ('s3://cardflow-lake-raw/transactions/');

CREATE FILE FORMAT IF NOT EXISTS CARDFLOW.RAW.NDJSON_GZ TYPE = JSON COMPRESSION = GZIP STRIP_OUTER_ARRAY = FALSE;

CREATE STAGE IF NOT EXISTS CARDFLOW.RAW.LAKE_STAGE
  URL = 's3://cardflow-lake-raw/transactions/' STORAGE_INTEGRATION = CARDFLOW_S3 FILE_FORMAT = CARDFLOW.RAW.NDJSON_GZ;

CREATE TABLE IF NOT EXISTS CARDFLOW.RAW.TRANSACTIONS_RAW (
  V VARIANT, SRC_FILE STRING, LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP());

-- Snowpipe with S3 event notifications (SQS ARN from SHOW PIPES -> notification_channel, wired in OpenTofu).
CREATE PIPE IF NOT EXISTS CARDFLOW.RAW.TRANSACTIONS_PIPE AUTO_INGEST = TRUE AS
  COPY INTO CARDFLOW.RAW.TRANSACTIONS_RAW (V, SRC_FILE)
  FROM (SELECT $1, METADATA$FILENAME FROM @CARDFLOW.RAW.LAKE_STAGE);
