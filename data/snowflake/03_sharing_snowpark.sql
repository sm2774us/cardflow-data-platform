-- Secure data sharing: partners see approved-rate metrics, never card tokens.
CREATE OR REPLACE SECURE VIEW CARDFLOW.CURATED.PARTNER_DAILY_METRICS AS
SELECT DATE_TRUNC('day', OCCURRED_AT) DAY, COUNTRY, COUNT(*) TXNS,
       AVG(IFF(DECISION = 'APPROVED', 1, 0)) APPROVAL_RATE, SUM(AMOUNT) VOLUME
FROM CARDFLOW.CURATED.TRANSACTIONS GROUP BY 1, 2;

CREATE SHARE IF NOT EXISTS CARDFLOW_PARTNER_SHARE;
GRANT USAGE ON DATABASE CARDFLOW TO SHARE CARDFLOW_PARTNER_SHARE;
GRANT USAGE ON SCHEMA CARDFLOW.CURATED TO SHARE CARDFLOW_PARTNER_SHARE;
GRANT SELECT ON VIEW CARDFLOW.CURATED.PARTNER_DAILY_METRICS TO SHARE CARDFLOW_PARTNER_SHARE;

-- Snowpark (Python) UDF: batch risk bucketing next to the data.
CREATE OR REPLACE FUNCTION CARDFLOW.CURATED.RISK_BUCKET(score FLOAT) RETURNS STRING
LANGUAGE PYTHON RUNTIME_VERSION = '3.11' HANDLER = 'bucket' AS
$$
def bucket(score):
    if score is None: return 'UNKNOWN'
    return 'HIGH' if score >= 0.85 else 'MEDIUM' if score >= 0.4 else 'LOW'
$$;
