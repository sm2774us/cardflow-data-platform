-- Incremental, idempotent promotion RAW -> CURATED using a Stream + Task with MERGE on event_id.
CREATE TABLE IF NOT EXISTS CARDFLOW.CURATED.TRANSACTIONS (
  EVENT_ID STRING PRIMARY KEY, EVENT_TYPE STRING, CARD_TOKEN STRING, MERCHANT_NAME STRING, MCC STRING,
  AMOUNT NUMBER(18,2), CURRENCY STRING, COUNTRY STRING, OCCURRED_AT TIMESTAMP_TZ,
  DECISION STRING, DECLINE_REASON STRING, RISK_SCORE NUMBER(5,4), CREATED_AT TIMESTAMP_TZ, LOADED_AT TIMESTAMP_LTZ);

CREATE STREAM IF NOT EXISTS CARDFLOW.RAW.TRANSACTIONS_STREAM ON TABLE CARDFLOW.RAW.TRANSACTIONS_RAW APPEND_ONLY = TRUE;

CREATE OR REPLACE TASK CARDFLOW.CURATED.PROMOTE_TRANSACTIONS
  WAREHOUSE = CARDFLOW_WH SCHEDULE = '1 MINUTE'
  WHEN SYSTEM$STREAM_HAS_DATA('CARDFLOW.RAW.TRANSACTIONS_STREAM')
AS
MERGE INTO CARDFLOW.CURATED.TRANSACTIONS t
USING (
  SELECT V:event_id::STRING EVENT_ID, V:event_type::STRING EVENT_TYPE, V:card_token::STRING CARD_TOKEN,
         V:merchant_name::STRING MERCHANT_NAME, V:mcc::STRING MCC, V:amount::NUMBER(18,2) AMOUNT,
         V:currency::STRING CURRENCY, V:country::STRING COUNTRY, V:occurred_at::TIMESTAMP_TZ OCCURRED_AT,
         V:decision::STRING DECISION, V:decline_reason::STRING DECLINE_REASON, V:risk_score::NUMBER(5,4) RISK_SCORE,
         V:created_at::TIMESTAMP_TZ CREATED_AT, LOADED_AT
  FROM CARDFLOW.RAW.TRANSACTIONS_STREAM
  QUALIFY ROW_NUMBER() OVER (PARTITION BY V:event_id ORDER BY LOADED_AT DESC) = 1   -- lake export is at-least-once
) s ON t.EVENT_ID = s.EVENT_ID
WHEN NOT MATCHED THEN INSERT VALUES (s.EVENT_ID, s.EVENT_TYPE, s.CARD_TOKEN, s.MERCHANT_NAME, s.MCC, s.AMOUNT, s.CURRENCY,
  s.COUNTRY, s.OCCURRED_AT, s.DECISION, s.DECLINE_REASON, s.RISK_SCORE, s.CREATED_AT, s.LOADED_AT);

ALTER TASK CARDFLOW.CURATED.PROMOTE_TRANSACTIONS RESUME;

-- Data-quality gate on the warehouse side: fails loudly if curated data drifts (run by a downstream task / CI).
CREATE OR REPLACE VIEW CARDFLOW.CURATED.DQ_VIOLATIONS AS
SELECT EVENT_ID, 'AMOUNT_RANGE' RULE FROM CARDFLOW.CURATED.TRANSACTIONS WHERE AMOUNT <= 0 OR AMOUNT > 1000000
UNION ALL SELECT EVENT_ID, 'MCC_FORMAT' FROM CARDFLOW.CURATED.TRANSACTIONS WHERE NOT REGEXP_LIKE(MCC, '\\d{4}');
